    private val common: Set<Char> = COMMON.toSet()

    /** 中文标点、全角符号 */
    private const val PUNCT = "，。、；：？！“”‘’（）《》〈〉【】「」『』—…·～　％＃＠＆＊－＋＝／＼｜"

    fun of(text: String, limit: Int = 64 * 1024): Double {
        val n = minOf(text.length, limit)
        if (n == 0) return 0.0
        var score = 0.0
        for (i in 0 until n) {
            val c = text[i]
            score += when {
                c == '\n' || c == '\r' || c == '\t' -> 1.0
                c.code in 0x20..0x7E -> 1.0
                c in common -> 1.0
                c in PUNCT -> 1.0
                c.code in 0xFF01..0xFF5E -> 0.8                 // 全角 ASCII
                c.code in 0x4E00..0x9FFF -> 0.25                // 其他常见区汉字（生僻）
                c.code in 0x3400..0x4DBF -> 0.0                 // 扩展 A：正文里极少
                c.code in 0x3040..0x30FF -> 0.0                 // 日文假名
                c.code in 0x0370..0x03FF || c.code in 0x0400..0x04FF -> 0.0 // 希腊、俄文
                c.code < 0x20 || c.code in 0x7F..0x9F -> -1.0   // 控制字符
                c.code in 0xE000..0xF8FF || c == '\uFFFD' -> -1.0 // 私用区、替换字符
                Character.isSurrogate(c) -> 0.0
                else -> 0.3                                     // 其他（拉丁扩展、emoji 等）
            }
        }
        return score / n
    }
}
