package com.example.yhviewer

import android.os.SystemClock
import android.util.Log
import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.platform.app.InstrumentationRegistry
import kotlinx.coroutines.runBlocking
import org.junit.Assert.*
import org.junit.Test
import org.junit.runner.RunWith
import java.io.File

/** One generated <32 MiB repository benchmark; no machine-specific timing assertions. */
@RunWith(AndroidJUnit4::class)
class V11TxtPerformanceTest {
    @Test fun generatedThirtyMiBTxtUsesIndexAndRebuildsLegacyIndex() = runBlocking {
        val context = InstrumentationRegistry.getInstrumentation().targetContext
        val fixtures = V11GeneratedFixtures(context)
        val repo = ShelfRepository(context, AppDatabase.get(context))
        val source = fixtures.file("txt")
        fun phase(name: String) {
            val runtime = Runtime.getRuntime()
            Log.i("V11Perf", "phase=$name javaUsed=${runtime.totalMemory() - runtime.freeMemory()} nativeAllocated=${android.os.Debug.getNativeHeapAllocatedSize()}")
        }
        try {
            // Buffered generation keeps the test itself from retaining a full-book string.
            val line = ("山海来信 mixed UTF8 line 0123456789 ".repeat(10) + "\r\n").toByteArray()
            source.outputStream().buffered().use { out ->
                repeat(4000) { chapter ->
                    out.write("第${chapter + 1}章 Performance $chapter\r\n".toByteArray())
                    repeat(7800 / line.size) { out.write(line) }
                }
            }
            assertTrue("About 30 MiB, inside normal TXT cap: ${source.length()}", source.length() in 28L * 1024 * 1024 until 32L * 1024 * 1024)
            phase("generated bytes=${source.length()}")
            phase("import-start")
            var start = SystemClock.elapsedRealtimeNanos()
            val id = fixtures.import(source)
            val importNs = SystemClock.elapsedRealtimeNanos() - start
            phase("import-done")
            val row = checkNotNull(AppDatabase.get(context).bookDao().get(id))
            val index = File(context.filesDir, "txt-index/${row.localFile}.idx")
            assertTrue("Import creates the normal index", index.isFile)
            // Artificial past timestamp makes a rebuild observable even on coarse filesystems.
            assertTrue(index.setLastModified(1_600_000_000_000))
            val indexTime = index.lastModified()
            val indexBytes = index.readBytes()
            phase("indexed-open-start")
            start = SystemClock.elapsedRealtimeNanos()
            val indexed = repo.open(id) as OpenedDoc.Txt
            val indexedNs = SystemClock.elapsedRealtimeNanos() - start
            phase("indexed-open-done")
            assertEquals(4000, indexed.chapterCount)
            assertEquals("Valid-index open must not rebuild", indexTime, index.lastModified())
            assertArrayEquals(indexBytes, index.readBytes())
            // TxtBook has no public cache diagnostic: inspect its storage contract before reads.
            val memory = TxtBook::class.java.getDeclaredField("inMemory").apply { isAccessible = true }
            val cache = TxtBook::class.java.getDeclaredField("cache").apply { isAccessible = true }
            assertNull("Valid UTF8 index must be file-backed", memory.get(indexed.book))
            assertTrue("Opening the index must not read chapter bodies", (cache.get(indexed.book) as Map<*, *>).isEmpty())
            listOf(0, 1999, 3999).forEach { assertTrue(indexed.book.text(it).contains("山海来信")) }
            assertTrue(index.delete())
            phase("legacy-rebuild-start")
            start = SystemClock.elapsedRealtimeNanos()
            val legacy = repo.open(id) as OpenedDoc.Txt
            val legacyNs = SystemClock.elapsedRealtimeNanos() - start
            phase("legacy-rebuild-done")
            assertTrue("Old-book open rebuilds missing index", index.isFile)
            assertEquals(4000, legacy.chapterCount)
            assertEquals(indexed.book.text(1999), legacy.book.text(1999))
            val rebuiltTime = index.lastModified()
            phase("hot-open-start")
            start = SystemClock.elapsedRealtimeNanos()
            val hot = repo.open(id) as OpenedDoc.Txt
            val hotNs = SystemClock.elapsedRealtimeNanos() - start
            phase("hot-open-done")
            assertEquals(4000, hot.chapterCount)
            assertEquals(rebuiltTime, index.lastModified())
            assertFalse(hot.book.text(3999).isBlank())
            Log.i("V11Perf", "flavor=${BuildConfig.FLAVOR} bytes=${source.length()} chapters=4000 importNs=$importNs indexedOpenNs=$indexedNs legacyRebuildNs=$legacyNs hotOpenNs=$hotNs indexMetadataOnly=true")
            repo.delete(id)
            assertFalse("Delete removes owned TXT index", index.exists())
        } finally { fixtures.clean() }
    }
}
